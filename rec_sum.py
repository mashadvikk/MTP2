"""Задание 9 (повышенная сложность): рекурсивная сумма чисел.

Сумма натуральных чисел от 1 до n задаётся рекуррентно:
S(1) = 1, S(n) = n + S(n - 1). Функция вызывает сама себя, уменьшая n,
пока не дойдёт до базового случая. Результат проверяется формулой
Гаусса n(n + 1) / 2. Тем же приёмом считается сумма цифр числа.
"""


def rec_sum(n):
    """Сумма 1 + 2 + ... + n, вычисленная рекурсией.

    >>> rec_sum(1)
    1
    >>> rec_sum(10)
    55
    >>> rec_sum(0)
    0
    """
    if n <= 0:
        return 0
    return n + rec_sum(n - 1)


def rec_sum_range(a, b):
    """Сумма целых чисел от a до b включительно (рекурсия по a).

    >>> rec_sum_range(3, 7)
    25
    >>> rec_sum_range(5, 4)
    0
    """
    if a > b:
        return 0
    return a + rec_sum_range(a + 1, b)


def digit_sum(n):
    """Сумма цифр числа: последняя цифра + сумма цифр остальной части.

    >>> digit_sum(2026)
    10
    >>> digit_sum(7)
    7
    """
    n = abs(n)
    if n < 10:
        return n
    return n % 10 + digit_sum(n // 10)


def gauss(n):
    """Формула Гаусса для проверки: n(n + 1) / 2."""
    return n * (n + 1) // 2


if __name__ == "__main__":
    for n in (5, 10, 100, 500):
        print(f"n = {n:>3}: рекурсия {rec_sum(n):>6}, "
              f"формула {gauss(n):>6}")
    print("Сумма от 3 до 7:", rec_sum_range(3, 7))
    print("Сумма цифр 2026:", digit_sum(2026))
